"""Bundle reviewed JSON fixtures for VM/Chrome tests without runtime file I/O."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
result = "// Generated by tool/generate_migration_fixtures.py; edit JSON fixtures instead.\nconst migrationFixtures = <String, String>{\n"
for path in sorted((root / 'test/fixtures/migrations').glob('*.json')):
    value = json.dumps(json.loads(path.read_text()), ensure_ascii=False, separators=(',', ':'))
    result += f"  '{path.stem}':\n      r'''{value}''',\n"
result += '};\n'
target = root / 'test/helpers/migration_fixtures.dart'
if args.check:
    if not target.exists() or target.read_text() != result:
        raise SystemExit('Migration fixture bundle is stale; run generator.')
else:
    target.write_text(result)
